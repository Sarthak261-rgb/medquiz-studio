"""Teaching images from Stable Diffusion 1.5, with and without the OpenStax LoRA.

Both arms use the same prompts and the same seeds, so any difference comes from the
LoRA. Every image carries a visible SYNTHETIC stamp and EXIF metadata saying it is
generated and educational, so it can never be passed off as a real patient image."""

from __future__ import annotations

import time
from collections.abc import Callable
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

from ..config import ImagesCfg
from ..energy import StageTracker, gpu_counter, joules_since
from ..runs import RunDir

# (id, what the image should show). Kept to structures a first-year text teaches.
SUBJECTS = [
    ("heart-anterior", "the anterior view of the human heart with the great vessels"),
    ("heart-chambers", "a frontal section of the human heart showing the four chambers and the valves"),
    ("conduction", "the conduction system of the heart: sinoatrial node, atrioventricular node and Purkinje fibers"),
    ("coronary", "the coronary arteries on the surface of the heart"),
    ("heart-wall", "the layers of the heart wall and the pericardium"),
    ("resp-system", "the human respiratory system: nasal cavity, pharynx, larynx, trachea, bronchi and lungs"),
    ("bronchial-tree", "the bronchial tree branching into bronchioles"),
    ("alveoli", "alveoli surrounded by pulmonary capillaries"),
    ("lungs-pleura", "the lungs and the pleura inside the thoracic cavity"),
    ("larynx", "the larynx, anterior view"),
    ("diaphragm", "the diaphragm and rib cage during inspiration"),
    ("vessels", "the walls of an artery, a vein and a capillary compared"),
]

NEGATIVE = "photo, photograph, photorealistic, text, letters, watermark, signature, blurry, deformed, low quality"


def prompt_for(subject: str, trigger: str) -> str:
    return f"{trigger}, medical textbook illustration of {subject}, clean flat colors, white background"


def stamp(img: Image.Image, text: str) -> Image.Image:
    """A banner inside the image itself, so a crop of the middle is the only way to lose it."""
    img = img.convert("RGB")
    draw = ImageDraw.Draw(img)
    h = max(18, img.height // 24)
    try:
        font = ImageFont.load_default(size=int(h * 0.62))
    except TypeError:  # Pillow < 10.1
        font = ImageFont.load_default()
    draw.rectangle([0, img.height - h, img.width, img.height], fill=(20, 20, 20))
    draw.text((8, img.height - h + (h - h * 0.62) / 2 - 1), text, fill=(255, 255, 255), font=font)
    return img


def save_with_metadata(img: Image.Image, path: Path, prompt: str, seed: int, model: str, stamp_text: str) -> None:
    exif = Image.Exif()
    exif[0x010E] = f"{stamp_text}. Generated by {model}, seed {seed}. Prompt: {prompt}"  # ImageDescription
    exif[0x0131] = "MedQuiz Studio"  # Software
    exif[0x8298] = "Synthetic image, CC BY-NC-SA 4.0 (trained on OpenStax A&P 2e figures)"  # Copyright
    img.save(path, "JPEG", quality=90, exif=exif.tobytes())


def load_pipeline(cfg: ImagesCfg, lora_dir: Path | None = None):
    import torch
    from diffusers import DPMSolverMultistepScheduler, StableDiffusionPipeline

    pipe = StableDiffusionPipeline.from_pretrained(
        cfg.base_model,
        torch_dtype=torch.float16,
        variant="fp16",
        # the NSFW filter blacks out anatomy diagrams; every output is reviewed anyway
        safety_checker=None,
        requires_safety_checker=False,
    )
    pipe.scheduler = DPMSolverMultistepScheduler.from_config(pipe.scheduler.config)
    pipe = pipe.to("cuda")
    pipe.enable_attention_slicing()
    pipe.set_progress_bar_config(disable=True)
    if lora_dir is not None:
        pipe.load_lora_weights(str(lora_dir))
    return pipe


def generate_arm(
    cfg: ImagesCfg, run: RunDir, arm: str, lora_dir: Path | None, progress: Callable[[str], None] = print
) -> int:
    """Resumable: images already listed in images.jsonl are skipped."""
    import torch

    done = {r["id"] for r in run.read("images.jsonl")}
    todo = [(sid, subj, seed) for sid, subj in SUBJECTS for seed in cfg.seeds if f"{arm}-{sid}-{seed}" not in done]
    if not todo:
        progress(f"{arm}: nothing to do")
        return 0
    (run.path / "images").mkdir(exist_ok=True)
    pipe = load_pipeline(cfg, lora_dir)
    with StageTracker(run, f"generate_{arm}") as tracker:
        for n, (sid, subj, seed) in enumerate(todo, 1):
            prompt = prompt_for(subj, cfg.trigger)
            start = gpu_counter().millijoules()
            t0 = time.perf_counter()
            image = pipe(
                prompt,
                negative_prompt=NEGATIVE,
                num_inference_steps=cfg.steps,
                guidance_scale=cfg.guidance,
                height=cfg.resolution,
                width=cfg.resolution,
                generator=torch.Generator("cuda").manual_seed(seed),
            ).images[0]
            seconds = time.perf_counter() - t0
            iid = f"{arm}-{sid}-{seed}"
            name = f"images/{iid}.jpg"
            save_with_metadata(stamp(image, cfg.stamp), run.path / name, prompt, seed, cfg.base_model, cfg.stamp)
            run.append(
                "images.jsonl",
                {
                    "id": iid,
                    "arm": arm,
                    "subject_id": sid,
                    "subject": subj,
                    "prompt": prompt,
                    "negative_prompt": NEGATIVE,
                    "seed": seed,
                    "file": name,
                    "model": cfg.base_model,
                    "lora": str(lora_dir.relative_to(run.path)) if lora_dir else None,
                    "steps": cfg.steps,
                    "guidance": cfg.guidance,
                    "seconds": round(seconds, 3),
                    "gpu_joules": joules_since(start),
                    "synthetic_stamp": cfg.stamp,
                },
            )
            tracker.tick()
            progress(f"  [{n}/{len(todo)}] {iid} {seconds:4.1f}s")
    del pipe
    torch.cuda.empty_cache()
    return len(todo)
